import { test, expect } from "@playwright/test";
test.skip(process.env.NEXT_PUBLIC_YETH_RECOVERY_PREVIEW !== "true", "Requires the explicit mock recovery milestone.");

test("milestones, live countdown, keyboard tabs and holder distribution", async ({ page }) => {
  await page.goto("/yeth");
  await expect(page.getByRole("progressbar")).toHaveAttribute("aria-valuemin", "36");
  await expect(page.getByTestId("milestone-50")).toContainText("50%");
  await expect(page.getByTestId("milestone-50").locator("time")).toHaveAttribute("datetime", /20\d{2}-\d{2}-\d{2}T/);
  await page.getByTestId("milestone-100").hover();
  await expect(page.getByRole("tooltip").filter({ hasText: "About 7.1 years from today" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("tooltip").filter({ hasText: "About 7.1 years from today" })).toBeHidden();
  await expect(page.getByTestId("hold-comparison")).toHaveText("Wait about 2.8 years to reach 69.0%");
  const timer = await page.getByTestId("auction-timer").textContent();
  await expect(page.getByTestId("auction-timer")).not.toHaveText(timer!);
  await page.getByRole("tab", { name: "Auction", exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("tab", { name: "Recovery progress" })).toBeFocused();
  await expect(page.getByRole("heading", { name: "Time to full recovery" })).toBeVisible();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("heading", { name: "Where recovery capital works" })).toBeVisible();
  await page.getByRole("tab", { name: "Holders", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Who still holds recovery shares" })).toBeVisible();
  await expect(page.getByRole("table").getByRole("row")).toHaveCount(49);
  await expect(page.getByText("1,000 ETH", { exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Holders", exact: true }).focus();
  await page.keyboard.press("End");
  await expect(page.getByRole("heading", { name: "Contracts", exact: true })).toBeVisible();
  await expect(page.getByRole("tabpanel").getByRole("button", { name: "Copy contract address" })).toHaveCount(6);
  await expect(page.getByRole("tabpanel").getByRole("link", { name: /View Ethereum address 0x26868/ })).toHaveAttribute("href", /etherscan.io\/address\/0x26868/i);
  await page.getByRole("tab", { name: "FAQ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "What risks do I take by holding?" })).toBeVisible();
  await page.getByLabel("Preview state").selectOption("flat");
  await expect(page.getByTestId("milestone-100")).toContainText("No estimate");
});

