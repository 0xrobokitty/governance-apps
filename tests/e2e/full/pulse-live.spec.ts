import { expect, test } from "@playwright/test";
import {marketFixture} from "../../fixtures/pulse-market-history";
import {flexFixture} from "../../fixtures/pulse-flex";
import {globalCapitalFixture} from "../../fixtures/pulse-global-capital";
import {tvlFixture} from "../../fixtures/pulse-tvl";
import fixture from "../../fixtures/pulse-live.json";
test.skip(process.env.NEXT_PUBLIC_ENABLE_PULSE !== "true", "Pulse live review is opt-in.");
test("Pulse live feed uses nine cards, real observations and visible gaps", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.route("**/api/pulse-data", route => route.fulfill({ json: fixture }));
  await page.goto("/pulse");
  await expect(page.getByRole("heading", {name:"Pulse", exact:true})).toBeVisible();
  await expect(page.getByTestId("pulse-live-card")).toHaveCount(10);
  await expect(page.getByText("Illustrative data · not live", {exact:true})).toHaveCount(0);
  await expect(page.getByRole("heading",{name:"Vault TVL",exact:true})).toBeVisible();
  await expect(page.getByRole("heading", {name:"Product movers", exact:true})).toBeVisible();
  await expect(page.getByRole("heading", {name:"Net vault flows", exact:true})).toBeVisible();
  await expect(page.getByRole("heading", {name:"Harvests & fees", exact:true})).toHaveCount(0);
  await expect(page.getByRole("combobox")).toHaveCount(0);
  await page.getByRole("button",{name:"365D",exact:true}).click();
  await expect(page.getByRole("button",{name:"365D",exact:true})).toHaveAttribute("aria-pressed","true");
  await page.getByRole("tab",{name:"Peg",exact:true}).click();
  const lockers=page.getByTestId("pulse-live-card").filter({has:page.getByRole("heading",{name:"yLockers",exact:true})});
  await expect(page.getByRole("tab",{name:"Net deposits",exact:true})).toHaveCount(0);
  await lockers.getByText("Details",{exact:true}).click();
  await expect(page.getByRole("dialog")).toContainText("Sale quote for 10,000");
  await page.keyboard.press("Escape");
  await expect(lockers.getByRole("button",{name:"Details: yLockers",exact:true})).toBeFocused();
  await expect(page.getByRole("table",{name:"Product movers"})).toBeVisible();
  await expect(page.getByRole("tab", {name:"Activity",exact:true})).toHaveAttribute("aria-selected","true");
  await expect(page.getByRole("tabpanel", {name:"Activity",exact:true})).toContainText("All supported chains · all assets");
  await expect(page.getByRole("tab",{name:"Net flows",exact:true})).toHaveCount(0);
  await page.setViewportSize({width:1920,height:1080});
  await page.getByRole("button", {name:"Wall view",exact:true}).click();
  const lastCard = page.getByTestId("pulse-live-card").last();
  expect((await lastCard.boundingBox())!.y + (await lastCard.boundingBox())!.height).toBeLessThanOrEqual(1080);
  const moversCard=page.getByTestId("pulse-live-card").filter({has:page.getByRole("heading",{name:"Product movers",exact:true})});
  const moversBody=await moversCard.getByRole("table").boundingBox();
  const moversBox=await moversCard.boundingBox();
  expect(moversBody!.y+moversBody!.height).toBeLessThanOrEqual(moversBox!.y+moversBox!.height);
  await expect.poll(() => page.getByTestId("pulse-chart").first().locator("svg").evaluate((svg: SVGSVGElement) => {
    const rect=svg.getBoundingClientRect(), view=svg.viewBox.baseVal;
    return Math.abs(rect.width/view.width-rect.height/view.height);
  })).toBeLessThan(0.01);
  await page.screenshot({path:testInfo.outputPath("pulse-history-wall.png")});
  await page.getByRole("button", {name:"Exit wall view",exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
test("Pulse does not replace failed live data with illustrative metrics", async ({ page }) => {
  await page.route("**/api/pulse-data", route => route.fulfill({status:503,json:{error:"unavailable"}}));
  await page.goto("/pulse");
  await expect(page.getByText(/Pulse is not available yet/)).toBeVisible();
  await expect(page.getByTestId("pulse-live-card")).toHaveCount(0);
});

test("Pulse global overview keeps chain and price detail inside compact cards",async({page},testInfo)=>{
  const f=globalCapitalFixture();
  const tvl=tvlFixture().tvlHistory;
  const history=tvl.history.map(p=>({...p,chains:tvl.source.chains.map(c=>({chainId:c.chainId,value:(Number(p.value)/7).toFixed(2)}))}));
  const source=f.metrics.find(m=>m.latest)!;
  const governance=[["yfi.styfi_direct",100],["yfi.styfix",200],["yfi.veyfi_migrated",300],["yfi.liquid_lockers_backing",400],["yfi.participating",1000],["yfi.participation_rate_bps",250]].map(([id,value])=>{
    const point={...source.latest!,observedAt:f.generatedAt,value:String(value)};
    return {...source,id:String(id),label:String(id),unit:"YFI",status:"available",history:[point],latest:point};
  });
  await page.route("**/api/pulse-data",route=>route.fulfill({json:{...f,tvlHistory:{...tvl,history,latest:history.at(-1)},metrics:[...f.metrics.filter(m=>!governance.some(g=>g.id===m.id)),...governance]}}));
  await page.setViewportSize({width:1920,height:1080});
  await page.goto("/pulse");
  await expect(page.getByTestId("pulse-live-card")).toHaveCount(10);
  await expect(page.getByRole("combobox")).toHaveCount(0);
  for(const card of await page.getByTestId("pulse-live-card").all()) await expect(card.getByRole("button",{name:/^Details:/})).toHaveCount(1);
  const tvlCard=page.getByTestId("pulse-live-card").filter({has:page.getByRole("heading",{name:"Vault TVL",exact:true})});
  await expect(tvlCard.getByTestId("pulse-area")).toHaveCount(7);
  const gov=page.getByTestId("pulse-live-card").filter({has:page.getByRole("heading",{name:"YFI governance",exact:true})});
  await expect(gov.getByTestId("pulse-area")).toHaveCount(4);
  await expect(gov.locator("strong")).toHaveText("1,000");
  await page.getByRole("tab",{name:"Flow balance",exact:true}).click();
  await expect(page.getByRole("tabpanel",{name:"Flow balance",exact:true})).toContainText("60%");
  await page.getByRole("tab",{name:"Net flows",exact:true}).click();
  await expect(page.getByRole("tabpanel",{name:"Net flows",exact:true})).toContainText("$");
  await page.getByRole("button",{name:"Wall view",exact:true}).click();
  const last=await page.getByTestId("pulse-live-card").last().boundingBox();
  expect(last!.y+last!.height).toBeLessThanOrEqual(1080);
  await page.screenshot({path:testInfo.outputPath("pulse-global-wall.png")});
  await page.getByRole("button",{name:"Exit wall view",exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath("pulse-global-mobile.png"),fullPage:true});
});

